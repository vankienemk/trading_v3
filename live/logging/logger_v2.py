"""
logger_v2.py - Paper Trading V2 Logger Module (SQLite + Ring Buffer)

Stores every signal-to-exit lifecycle for any asset (XAUUSD, EURUSD, etc.).
Written BEFORE sending the order (entry_planned / stop / target known),
then UPDATED after the order fills and exits.

Adds a user_action_log table for tracking GUI user actions.
Adds a system_logs table for the centralized System Logger (GUI_REWORK §5).

Schema columns for the signals table (spec section 5):

  event_id               TEXT PRIMARY KEY   - UUID v4, generated by log_signal()
  asset                  TEXT               - e.g. "XAUUSD" or "EURUSD"
  signal_time            TEXT (ISO-8601)    - when the signal engine fired
  confirmation_time      TEXT (ISO-8601)    - when the signal was confirmed
  features_json          TEXT               - JSON blob of signal features
  rule_score             REAL               - rule-based entry score
  model_probability      REAL               - model probability (0-1)
  entry_planned          REAL               - planned entry price
  stop_planned           REAL               - planned stop-loss price
  target_planned         REAL               - planned take-profit price
  order_sent_time        TEXT (ISO-8601)    - when the order was dispatched
  entry_actual           REAL               - actual fill price
  slippage_actual        REAL               - slippage = entry_actual - entry_planned (signed)
  exit_time              TEXT (ISO-8601)    - when the trade exited
  exit_price             REAL               - actual exit price
  exit_reason            TEXT               - e.g. "take_profit", "stop_loss", "manual_close"
  mfe_r                  REAL               - maximum favourable excursion in R multiples
  mae_r                  REAL               - maximum adverse excursion in R multiples
  net_result_r           REAL               - net result in R multiples
  automation_level       INTEGER            - 0=manual, 1=semi-auto, 2=full-auto
  kill_switch_status_at_signal  INTEGER     - 0=off, 1=on (blocking)

user_action_log table schema:

  id                     INTEGER PRIMARY KEY AUTOINCREMENT
  timestamp              TEXT (ISO-8601)    - when the action occurred
  action_type            TEXT               - e.g. "change_automation_level",
                                              "override_kill_switch",
                                              "send_order_click",
                                              "emergency_stop_toggle",
                                              "set_mcp_token",
                                              "reconnect_mcp"
  details_json           TEXT               - arbitrary JSON with action-specific fields

system_logs table schema (GUI_REWORK §5.7):

  id                     INTEGER PRIMARY KEY AUTOINCREMENT
  timestamp              TEXT (ISO-8601)    - when the log was created
  level                  TEXT NOT NULL      - DEBUG / INFO / WARNING / ERROR / CRITICAL
  source                 TEXT NOT NULL      - SignalEngine, RiskGuard, Execution, MCP, System, UserAction, etc.
  symbol                 TEXT               - instrument name or empty string
  message                TEXT NOT NULL      - human-readable log message
  extra_json             TEXT               - optional JSON blob for additional context

Dependencies: Python 3.10+ standard library only (sqlite3, uuid, datetime, collections, threading).
"""

import json
import sqlite3
import threading
import uuid
from collections import deque
from datetime import datetime, timezone
