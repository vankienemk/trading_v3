def _row_to_dict(row: sqlite3.Row) -> dict[str, Any]:
    """Convert a ``sqlite3.Row`` to a plain ``dict``.

    If *row* is ``None``, returns an empty dict (should not happen with
    valid queries, but guards against callers that check truthiness).
    """
    if row is None:
        return {}
    return dict(row)