DEFAULT_DB_PATH = Path(__file__).resolve().parent.parent / "db" / "paper_trading_v2.db"


def _iso_now() -> str:
    """Return current UTC timestamp as ISO-8601 string."""
    return datetime.now(timezone.utc).isoformat()


