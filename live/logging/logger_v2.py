def log_signal(
    asset: str,
    signal_time: str,
    confirmation_time: str,
    features_json: str,
    rule_score: float,
    model_probability: float,
    entry_planned: float,
    stop_planned: float,
    target_planned: float,
    order_sent_time: str,
    automation_level: int,
    kill_switch_status_at_signal: int,
    *,
    event_id: Optional[str] = None,
    db_path: Optional[str] = None,
) -> dict[str, Any]:
    """Insert a new signal record and return it as a dictionary.

    Call this **BEFORE** sending the order to the execution layer so that
    the planned entry / stop / target are persisted before any fill data
    arrives.

    Args:
        asset: Instrument name, e.g. ``"XAUUSD"`` or ``"EURUSD"``.
        signal_time: ISO-8601 timestamp when the signal engine fired.
        confirmation_time: ISO-8601 timestamp when the signal was confirmed.
        features_json: Arbitrary JSON blob of signal features.
        rule_score: Scalar score from the rule-based component.
        model_probability: Model probability in [0, 1].
        entry_planned: Planned entry price.
        stop_planned: Planned stop-loss price.
        target_planned: Planned take-profit price.
        order_sent_time: ISO-8601 timestamp when the order was dispatched.
        automation_level: 0=manual, 1=semi-auto, 2=full-auto.
        kill_switch_status_at_signal: 0=off, 1=on.
        event_id: Optional caller-supplied UUID; a new UUID v4 is generated
                  if omitted.
        db_path: Override the database path.

    Returns:
        A dictionary representation of the inserted row.
    """
    eid = event_id if event_id is not None else str(uuid.uuid4())
    conn = _get_connection(db_path)
    try:
        conn.execute(
            """
            INSERT INTO signals (
                event_id, asset, signal_time, confirmation_time,
                features_json, rule_score, model_probability,
                entry_planned, stop_planned, target_planned,
                order_sent_time, automation_level,
                kill_switch_status_at_signal
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                eid,
                asset,
                signal_time,
                confirmation_time,
                features_json,
                rule_score,
                model_probability,
                entry_planned,
                stop_planned,
                target_planned,
                order_sent_time,
                automation_level,
                kill_switch_status_at_signal,
            ),
        )
        conn.commit()
        return _row_to_dict(
            conn.execute(
                "SELECT * FROM signals WHERE event_id = ?", (eid,)
            ).fetchone()
        )
    finally:
        conn.close()


def update_order_result(
    event_id: str,
    entry_actual: float,
    slippage_actual: float,
    exit_time: str,
    exit_price: float,
    exit_reason: str,
    mfe_r: float,
    mae_r: float,
    net_result_r: float,
    *,
    db_path: Optional[str] = None,
) -> Optional[dict[str, Any]]:
    """Update a previously logged signal with actual fill and exit data.

    Call this **AFTER** the trade closes to fill in the execution outcome.

    Args:
        event_id: The UUID of the signal to update.
        entry_actual: Actual fill price.
        slippage_actual: Signed difference (entry_actual - entry_planned).
        exit_time: ISO-8601 timestamp of exit.
        exit_price: Price at exit.
        exit_reason: Categorical reason.
        mfe_r: Maximum favourable excursion in R multiples.
        mae_r: Maximum adverse excursion in R multiples.
        net_result_r: Net result in R multiples.
        db_path: Override the database path.

    Returns:
        The updated row as a dictionary, or ``None`` if *event_id* is not
        found.
    """
    conn = _get_connection(db_path)
    try:
        cursor = conn.execute(
            """
            UPDATE signals
            SET entry_actual      = ?,
                slippage_actual   = ?,
                exit_time         = ?,
                exit_price        = ?,
                exit_reason       = ?,
                mfe_r             = ?,
                mae_r             = ?,
                net_result_r      = ?
            WHERE event_id = ?
            """,
            (
                entry_actual,
                slippage_actual,
                exit_time,
                exit_price,
                exit_reason,
                mfe_r,
                mae_r,
                net_result_r,
                event_id,
            ),
        )
        conn.commit()
        if cursor.rowcount == 0:
            return None
        return _row_to_dict(
            conn.execute(
                "SELECT * FROM signals WHERE event_id = ?", (event_id,)
            ).fetchone()
        )
    finally:
        conn.close()


def log_user_action(
    action_type: str,
    details_json: Optional[str] = None,
    *,
    db_path: Optional[str] = None,
) -> dict[str, Any]:
    """Log a user action (GUI interaction) to the user_action_log table.

    Args:
        action_type: A short string identifying the action, e.g.
                     ``"change_automation_level"``, ``"override_kill_switch"``,
                     ``"send_order_click"``, ``"emergency_stop_toggle"``,
                     ``"set_mcp_token"``, ``"reconnect_mcp"``.
        details_json: Optional JSON string with action-specific fields.
        db_path: Override the database path.

    Returns:
        A dictionary representation of the inserted row.
    """
    now = _iso_now()
    conn = _get_connection(db_path)
    try:
        c = conn.execute(
            "INSERT INTO user_action_log (timestamp, action_type, details_json) VALUES (?, ?, ?)",
            (now, action_type, details_json),
        )
        conn.commit()
        row = conn.execute(
            "SELECT * FROM user_action_log WHERE id = ?", (c.lastrowid,)
        ).fetchone()
        return _row_to_dict(row)
    finally:
        conn.close()


def get_recent_trades(
    asset: str,
    n: int = 20,
    *,
    db_path: Optional[str] = None,
) -> list[dict[str, Any]]:
    """Return the *n* most recent trades for a given asset.

    Only rows that have an ``exit_time`` (i.e. completed trades) are
    returned, ordered by ``order_sent_time DESC``.

    This function is used by the Risk Guard module for block bootstrap
    kill-switch evaluation.

    Args:
        asset: Instrument name (e.g. ``"XAUUSD"``).
        n: Maximum number of rows (default 20).
        db_path: Override the database path.

    Returns:
        A list of row dictionaries (most recent first).
    """
    conn = _get_connection(db_path)
    try:
        rows = conn.execute(
            """
            SELECT * FROM signals
            WHERE asset = ? AND exit_time IS NOT NULL
            ORDER BY order_sent_time DESC
            LIMIT ?
            """,
            (asset, n),
        ).fetchall()
        return [_row_to_dict(r) for r in rows]
    finally:
        conn.close()


def get_all_trades(
    *,
    db_path: Optional[str] = None,
) -> list[dict[str, Any]]:
    """Return every signal row in the database.

    Rows are ordered by ``order_sent_time DESC`` so the most recent
    appears first.

    Args:
        db_path: Override the database path.

    Returns:
        A list of all row dictionaries.
    """
    conn = _get_connection(db_path)
    try:
        rows = conn.execute(
            "SELECT * FROM signals ORDER BY order_sent_time DESC"
        ).fetchall()
        return [_row_to_dict(r) for r in rows]
    finally:
        conn.close()


def get_user_actions(
    n: int = 100,
    *,
    db_path: Optional[str] = None,
) -> list[dict[str, Any]]:
    """Return the *n* most recent user action log entries.

    Args:
        n: Maximum number of rows (default 100).
        db_path: Override the database path.

    Returns:
        A list of row dictionaries (most recent first).
    """
    conn = _get_connection(db_path)
    try:
        rows = conn.execute(
            "SELECT * FROM user_action_log ORDER BY id DESC LIMIT ?",
            (n,),
        ).fetchall()
        return [_row_to_dict(r) for r in rows]
    finally:
        conn.close()


