"""Event → labeled dataset / trade records builder (guide sections 14-18, 26.3).

``build_event_labels`` is the canonical contract (``docs/INTERFACES.md``
section 6) for Pipeline 3: given the candle frame (with a causal ``atr``
column, added automatically when missing) and the sweep-event table, it adds,
one row per event:

* **identity** — ``event_id, event_time, direction`` (normalized to the
  canonical ``long``/``short``), ``level_id, level_price, atr`` (ATR at the
  sweep candle), ``entry_time, entry_price, stop_price, risk_price``;
* **targets** — ``target_{R}r`` for every reward multiple (``target_1r``,
  ``target_1_5r``, ``target_2r``);
* **excursions** — per horizon ``mfe_r_h{H}, mae_r_h{H}, close_return_r_h{H},
  max_close_return_r_h{H}, min_close_return_r_h{H}`` (guide 15/18; fixed
  window starting at the entry candle);
* **outcomes** — ``outcome_{R}r_h{H}`` for every (reward, horizon) combo,
  values ``tp | sl | time | ambiguous`` (canonical tokens,
  ``src/schema.py::OUTCOME_VALUES``; numeric labels 1/0/-1/NaN live in
  :mod:`src.labeling.triple_barrier` and map bijectively);
* **primary exit + costs** — for the primary combo
  (default ``(reward_r=2.0, horizon=16)`` = ``configs/baseline.yaml``
  ``model.target: outcome_2r_h16``): ``exit_time, exit_price, exit_reason,
  bars_held, ambiguous, bars_to_target, bars_to_stop, gross_result_r,
  cost_r, net_result_r``.

Entry mode (guide 14.1): baseline Phase 2 enters at the open of the candle
after the sweep (``entry.mode: next_open_after_sweep``).  When
``entry.mode: next_open_after_confirmation`` is configured the events must
carry the confirmation columns (``is_confirmed``, ``confirmation_time`` —
attached by Agent 3, Phase 5); confirmed events enter at the open after the
confirmation candle, unconfirmed ones are dropped as invalid.

Invalid events (guide 14.4 — ``risk <= 0``; plus ATR missing, entry beyond the
data, missing confirmation) are *dropped from the returned frame and reported*
in ``df.attrs["labeling_invalid"]`` / ``df.attrs["labeling_summary"]`` so the
ambiguity is never silent.  Nothing reads past the end of the candle frame.

Costs (guide 17) are applied on the raw geometry with exact formulas::

    gross_result_r = signed (exit_raw - entry_raw) / risk
    cost_r         = 2 * (half_spread_price + slippage_price) / risk
                     + commission_r          # commission in R units
    net_result_r   = gross_result_r - cost_r

``costs.half_spread_price`` / ``costs.slippage_price`` are PRICE units
(USD per oz of gold).  Data-engineering note (task t2): the raw MT5 SPREAD
column is in *points* (not price) and the parquet volume is tick volume; the
labeling pipeline reads neither — when a nonzero spread cost is configured the
caller must first convert points to price and put it under ``costs.*``.
Conversion reference (Data_Engineer, task t2): XAUUSD in this dataset quotes
with 2 decimals, so 1 price point = 0.01 USD/oz and
``half_spread_price = raw_spread_points * 0.01 / 2``; rows whose raw spread is
0 (5,215 rows, mostly 2022) need an explicit policy (e.g. floor by session
median) before real costs are enabled.  The legacy ``entry.spread_price`` /
``entry.slippage_price`` keys are rejected with a loud error if nonzero so
costs can never be silently understated.

``build_trade_records`` returns the same simulation in *long* form — one row
per (event, reward, horizon) — with the Agent-5 output schema (guide 5.6),
which the human-review stage (task t7) consumes for chart grouping.

Column names are generated by the helpers at the bottom of this module
(:func:`outcome_column`, :func:`target_column`, :func:`wide_schema_columns`)
so downstream consumers reference a single source of truth.

Causality of the decision bar (QA finding F1)
---------------------------------------------
Labeling treats ``event_time`` as *the* decision bar: entry is the open of the
candle right after it and every simulation is anchored there.  That bar must
therefore be causally decidable in real time — i.e. the first bar of a sweep
run.  Run-representative dedup rules such as t4's default
``deepest_penetration`` / ``strongest_reclaim`` pick a *later* bar of the same
run, which is only knowable in hindsight (intra-run look-ahead at the event
table level).  This module cannot repair that from the event table alone;
backtest/labeling runs must feed events generated with the causal rule
``group_rule="first"`` (or equivalently first-bar-of-run anchoring upstream,
Agent 3 / task t9).  Nothing in this module reads earlier or later candles of
the same run: every computation starts from the open of the candle after the
``event_time`` bar.
"""

