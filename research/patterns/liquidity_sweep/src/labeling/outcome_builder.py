def _prepare(
    candles: pd.DataFrame,
    events: pd.DataFrame,
    cfg: dict[str, Any],
) -> pd.DataFrame:
    """Validate inputs and ensure the candle frame carries a causal ``atr``."""
    if not isinstance(events, pd.DataFrame) or len(events) == 0:
        raise ValueError("events must be a non-empty DataFrame")
    required = [c for c in ("event_id", "event_time", "direction") if c not in events.columns]
    if required:
        raise ValueError(f"events missing required columns {required}")

    work = candles.copy()

    # The processed parquet artifact stores timestamps as a ``timestamp``
    # column on a RangeIndex; promote it to the canonical DatetimeIndex when
    # the frame has no time axis of its own (docs/SCHEMAS.md section 3).
    if not isinstance(work.index, pd.DatetimeIndex):
        if "timestamp" not in work.columns:
            raise ValueError(
                "candles must carry a datetime index (or a 'timestamp' column "
                "to promote); labeling needs a time axis to resolve events"
            )
        work = work.set_index("timestamp").sort_index()
        work = work[~work.index.duplicated(keep="first")]
    elif "timestamp" in work.columns:
        # Same time axis twice: keep the index as canonical, drop the column.
        if work["timestamp"].equals(pd.Series(work.index, index=work.index)):
            work = work.drop(columns=["timestamp"])

    if "atr" not in work.columns:
        from src.indicators.atr import add_atr  # local import: only when needed

        work = add_atr(work, period=cfg["atr_period"])
    validate_label_frame(work, func="build_event_labels")

    if cfg["entry_mode"] == "next_open_after_confirmation":
        missing = [
            c for c in ("is_confirmed", "confirmation_time") if c not in events.columns
        ]
        if missing:
            raise ValueError(
                "entry.mode is next_open_after_confirmation but events lack "
                f"confirmation columns {missing}; attach confirmations "
                "(Agent 3) or switch entry.mode to next_open_after_sweep"
            )
    return work


def _iter_simulated(
    work: pd.DataFrame,
    events: pd.DataFrame,
    cfg: dict[str, Any],
) -> Iterator[tuple[dict[str, Any] | None, dict[str, Any] | None]]:
    """Yield ``(wide_row_with_sims, invalid_record)`` for every event."""
    highs = work["high"].to_numpy(dtype=float)
    lows = work["low"].to_numpy(dtype=float)
    opens = work["open"].to_numpy(dtype=float)
    closes = work["close"].to_numpy(dtype=float)
    atr = work["atr"].to_numpy(dtype=float)
    times = work.index

    event_times = pd.DatetimeIndex(events["event_time"])
    positions = work.index.get_indexer(event_times)
    missing = int((positions < 0).sum())
    if missing:
        raise ValueError(
            f"{missing} event_time value(s) do not exist in the candle index; "
            "candles and events must come from the same frame"
        )

    for row_idx in range(len(events)):
        ev = events.iloc[row_idx]
        yield _simulate_event(
            highs=highs,
            lows=lows,
            opens=opens,
            closes=closes,
            atr=atr,
            times=times,
            event_id=ev["event_id"],
            event_time=ev["event_time"],
            raw_direction=ev["direction"],
            sweep_pos=int(positions[row_idx]),
            cfg=cfg,
            events=events,
            row_idx=row_idx,
        )


def _attach_invalid_attrs(out: pd.DataFrame, invalid_rows: list[dict[str, Any]]) -> None:
    """Attach audit metadata (config, dropped events, summary) to a result."""
    invalid_df = pd.DataFrame(invalid_rows)
    reasons: dict[str, int] = {}
    if len(invalid_df):
        reasons = invalid_df["reason"].value_counts().to_dict()
    out.attrs["labeling_invalid"] = invalid_df
    out.attrs["labeling_summary"] = {
        "n_invalid": len(invalid_df),
        "reasons": reasons,
    }


def build_event_labels(
    candles: pd.DataFrame,
    events: pd.DataFrame,
    config: Mapping[str, Any] | None = None,
) -> pd.DataFrame:
    """Pipeline 3 labeling entry point (contract ``docs/INTERFACES.md`` §6).

    Adds one row per *valid* event with the wide schema of
    :func:`wide_schema_columns` (identity, targets, per-horizon excursions,
    per-(reward,horizon) outcome tokens, primary exit + costs).  Invalid
    events (risk <= 0, missing ATR, no next bar, unconfirmed in
    confirmation-entry mode) are dropped and reported through the returned
    frame's ``attrs``:

    * ``attrs["labeling_config"]`` — the resolved config dict;
    * ``attrs["labeling_invalid"]`` — DataFrame of dropped events + reasons;
    * ``attrs["labeling_summary"]`` — ``{n_valid, n_invalid, reasons,
      n_ambiguous_primary, directions}``.
    """
    cfg = resolve_labeling_config(config)
    work = _prepare(candles, events, cfg)

    wide_rows: list[dict[str, Any]] = []
    invalid_rows: list[dict[str, Any]] = []
    for wide, invalid in _iter_simulated(work, events, cfg):
        if wide is not None:
            wide.pop(_SIMS_KEY, None)
            wide_rows.append(wide)
        else:
            assert invalid is not None
            invalid_rows.append(invalid)

    columns = wide_schema_columns(cfg)
    out = pd.DataFrame(wide_rows, columns=columns)
    out = out.sort_values("event_time", kind="stable").reset_index(drop=True)

    primary_col = outcome_column(cfg["primary_reward_r"], cfg["primary_horizon"])
    out.attrs["labeling_config"] = cfg
    _attach_invalid_attrs(out, invalid_rows)
    summary = dict(out.attrs["labeling_summary"])
    summary.update(
        {
            "n_valid": len(out),
            "n_ambiguous_primary": int((out[primary_col] == TOKEN_AMBIGUOUS).sum()),
            "directions": out["direction"].value_counts().to_dict(),
        }
    )
    out.attrs["labeling_summary"] = summary
    return out


def build_trade_records(
    candles: pd.DataFrame,
    events: pd.DataFrame,
    config: Mapping[str, Any] | None = None,
) -> pd.DataFrame:
    """Long-format trade records — one row per (event, reward, horizon).

    Columns follow the Agent-5 output schema (guide 5.6) plus ``reward_r`` /
    ``horizon`` / ``event_time`` keys; ``outcome`` holds the canonical token
    (``tp/sl/time/ambiguous``), ``mfe_r``/``mae_r`` are the excursions up to
    the exit (guide 16.2 semantics), ``net_result_r`` is cost-adjusted
    (guide 17).  Invalid events are dropped and reported through ``attrs``
    exactly as in :func:`build_event_labels`.
    """
    cfg = resolve_labeling_config(config)
    work = _prepare(candles, events, cfg)

    records: list[dict[str, Any]] = []
    invalid_rows: list[dict[str, Any]] = []
    for wide, invalid in _iter_simulated(work, events, cfg):
        if wide is None:
            assert invalid is not None
            invalid_rows.append(invalid)
            continue
        sims = wide.pop(_SIMS_KEY)
        direction = wide["direction"]
        risk = float(wide["risk_price"])
        cost = cost_in_r(
            risk=risk,
            half_spread_price=cfg["half_spread_price"],
            slippage_price=cfg["slippage_price"],
            commission_r=cfg["commission_r"],
        )
        for reward in cfg["reward_r_values"]:
            for horizon in cfg["horizons"]:
                sim = sims[(reward, horizon)]
                exit_price = float(sim["exit_price"])
                gross = gross_result_in_r(direction, wide["entry_price"], exit_price, risk)
                records.append(
                    {
                        "event_id": wide["event_id"],
                        "event_time": wide["event_time"],
                        "direction": direction,
                        "reward_r": float(reward),
                        "horizon": int(horizon),
                        "entry_time": wide["entry_time"],
                        "entry_price": wide["entry_price"],
                        "stop_price": wide["stop_price"],
                        "target_price": wide[target_column(reward)],
                        "risk_price": risk,
                        "outcome": outcome_to_token(float(sim["outcome"])),
                        "exit_time": sim["exit_time"],
                        "exit_price": exit_price,
                        "exit_reason": sim["exit_reason"],
                        "mfe_r": float(sim["mfe_r"]),
                        "mae_r": float(sim["mae_r"]),
                        "bars_held": int(sim["bars_held"]),
                        "net_result_r": (
                            float(gross - cost) if not math.isnan(gross) else float("nan")
                        ),
                        "ambiguous": bool(sim["ambiguous"]),
                    }
                )

    out = pd.DataFrame(records, columns=TRADE_RECORD_COLUMNS)
    out = out.sort_values(["event_time", "reward_r", "horizon"], kind="stable").reset_index(
        drop=True
    )
    out.attrs["labeling_config"] = cfg
    _attach_invalid_attrs(out, invalid_rows)
    summary = dict(out.attrs["labeling_summary"])
    summary.update(
        {
            "n_valid_events": int(out["event_id"].nunique()),
            "n_records": len(out),
        }
    )
    out.attrs["labeling_summary"] = summary
    return out
