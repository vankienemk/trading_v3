def _invalid_record(
    event_id: Any,
    event_time: Any,
    direction: str,
    reason: str,
) -> dict[str, Any]:
    return {
        "event_id": event_id,
        "event_time": event_time,
        "direction": direction,
        "reason": reason,
    }


def _simulate_event(
    highs: np.ndarray,
    lows: np.ndarray,
    opens: np.ndarray,
    closes: np.ndarray,
    atr: np.ndarray,
    times: pd.Index,
    event_id: Any,
    event_time: Any,
    raw_direction: str,
    sweep_pos: int,
    cfg: dict[str, Any],
    events: pd.DataFrame,
    row_idx: int,
) -> tuple[dict[str, Any] | None, dict[str, Any] | None]:
    """Run the full (rewards x horizons) simulation for one event.

    Returns ``(wide_row, invalid_record)`` — exactly one is not ``None``.
    The wide row carries the hidden ``_SIMS_KEY`` with every (reward, horizon)
    sim dict (needed by the long trade-records builder); callers strip it.
    """
    direction = normalize_direction(raw_direction)
    n = len(highs)

    if cfg["entry_mode"] == "next_open_after_confirmation":
        is_confirmed = bool(events["is_confirmed"].iloc[row_idx])
        if not is_confirmed:
            return None, _invalid_record(event_id, event_time, direction, "no_confirmation")
        confirmation_time = events["confirmation_time"].iloc[row_idx]
        conf_pos = _position_of(events, row_idx, "confirmation_time", confirmation_time, times)
        entry_pos = conf_pos + 1
        if conf_pos <= sweep_pos:
            return None, _invalid_record(
                event_id, event_time, direction, "confirmation_not_after_sweep"
            )
    else:
        entry_pos = sweep_pos + 1

    if entry_pos >= n:
        return None, _invalid_record(event_id, event_time, direction, "no_next_bar")

    entry_price = float(opens[entry_pos])
    if not math.isfinite(entry_price):
        return None, _invalid_record(event_id, event_time, direction, "entry_nan")

    atr_value = float(atr[sweep_pos])
    if direction == DIRECTION_LONG:
        sweep_extreme = float(lows[sweep_pos])
    else:
        sweep_extreme = float(highs[sweep_pos])

    # Stop/risk do not depend on the reward multiple; use any configured one.
    levels = compute_trade_levels(
        direction,
        entry_price=entry_price,
        sweep_extreme=sweep_extreme,
        atr_value=atr_value,
        reward_r=cfg["reward_r_values"][0],
        stop_buffer_atr=cfg["stop_buffer_atr"],
    )
    risk = levels["risk"]
    if math.isnan(risk):
        return None, _invalid_record(event_id, event_time, direction, "atr_missing")
    if not math.isfinite(risk) or risk <= 0:
        return None, _invalid_record(event_id, event_time, direction, "risk_le_0")
    stop = levels["stop"]

    targets: dict[float, float] = {}
    for reward in cfg["reward_r_values"]:
        targets[reward] = (
            entry_price + reward * risk
            if direction == DIRECTION_LONG
            else entry_price - reward * risk
        )

    # ---- fixed-window excursions per horizon (guide 15) -------------------
    excursions: dict[int, dict[str, Any] | None] = {}
    for horizon in cfg["horizons"]:
        excursions[horizon] = measure_excursions_arrays(
            highs=highs,
            lows=lows,
            closes=closes,
            entry_pos=entry_pos,
            horizon=horizon,
            direction=direction,
            entry_price=entry_price,
            risk=risk,
        )

    # ---- triple-barrier sims per (reward, horizon) (guide 16) -------------
    sims: dict[tuple[float, int], dict[str, Any]] = {}
    for reward in cfg["reward_r_values"]:
        for horizon in cfg["horizons"]:
            sim = label_event_arrays(
                highs=highs,
                lows=lows,
                opens=opens,
                closes=closes,
                atr=atr,
                times=times,
                event_pos=sweep_pos,
                direction=direction,
                entry_pos=entry_pos,
                horizon=horizon,
                stop_buffer_atr=cfg["stop_buffer_atr"],
                reward_r=reward,
                same_bar_policy=cfg["same_bar_policy"],
                time_barrier_result=cfg["time_barrier_result"],
            )
            if sim is None:  # defensive: everything was pre-validated
                return None, _invalid_record(event_id, event_time, direction, "sim_failed")
            sims[(reward, horizon)] = sim

    # ---- assemble the wide row -------------------------------------------
    entry_time = times[entry_pos]
    wide: dict[str, Any] = {
        "event_id": event_id,
        "event_time": event_time,
        "direction": direction,
        "level_id": _optional_value(events, row_idx, "level_id"),
        "level_price": _optional_value(events, row_idx, "level_price"),
        "atr": float(atr_value),
        "entry_time": entry_time,
        "entry_price": float(entry_price),
        "stop_price": float(stop),
        "risk_price": float(risk),
    }
    for reward, target in targets.items():
        wide[target_column(reward)] = float(target)
    for horizon in cfg["horizons"]:
        exc = excursions[horizon]
        if exc is None:  # pragma: no cover - guarded by valid risk/entry above
            continue
        wide[f"mfe_r_h{horizon}"] = exc["mfe_r"]
        wide[f"mae_r_h{horizon}"] = exc["mae_r"]
        wide[f"close_return_r_h{horizon}"] = exc["close_return_r"]
        wide[f"max_close_return_r_h{horizon}"] = exc["max_close_return_r"]
        wide[f"min_close_return_r_h{horizon}"] = exc["min_close_return_r"]
    for reward in cfg["reward_r_values"]:
        for horizon in cfg["horizons"]:
            wide[outcome_column(reward, horizon)] = outcome_to_token(
                sims[(reward, horizon)]["outcome"]
            )

    primary = sims[(cfg["primary_reward_r"], cfg["primary_horizon"])]
    wide.update(_exit_and_cost_columns(primary, direction, cfg))
    wide[_SIMS_KEY] = sims
    return wide, None


def _position_of(
    events: pd.DataFrame,
    row_idx: int,
    column: str,
    value: Any,
    times: pd.Index,
) -> int:
    """Locate an event/confirmation timestamp inside the candle index."""
    positions = times.get_indexer(pd.DatetimeIndex([value]))
    pos = int(positions[0])
    if pos < 0:
        raise ValueError(
            f"build_event_labels: {column} value {value} of event "
            f"{events['event_id'].iloc[row_idx]!r} does not exist in the "
            "candle index; candles and events must come from the same frame"
        )
    return pos


def _optional_value(events: pd.DataFrame, row_idx: int, column: str) -> Any:
    if column in events.columns:
        return events[column].iloc[row_idx]
    return float("nan")


def _exit_and_cost_columns(
    sim: dict[str, Any],
    direction: str,
    cfg: dict[str, Any],
) -> dict[str, Any]:
    """Primary-combo exit metadata plus gross/cost/net result in R."""
    exit_reason = sim["exit_reason"]
    exit_price = float(sim["exit_price"])
    risk = float(sim["risk"])
    ambiguous = bool(sim["ambiguous"])
    bars_held = int(sim["bars_held"])

    cost = cost_in_r(
        risk=risk,
        half_spread_price=cfg["half_spread_price"],
        slippage_price=cfg["slippage_price"],
        commission_r=cfg["commission_r"],
    )
    gross = gross_result_in_r(direction, sim["entry"], exit_price, risk)

    bars_to_target: float
    bars_to_stop: float
    if exit_reason == EXIT_REASON_TARGET:
        bars_to_target, bars_to_stop = bars_held, float("nan")
    elif exit_reason == EXIT_REASON_STOP:
        bars_to_target, bars_to_stop = float("nan"), bars_held
    else:  # time barrier or ambiguous: no single barrier was hit
        bars_to_target, bars_to_stop = float("nan"), float("nan")

    return {
        "exit_time": sim["exit_time"],
        "exit_price": exit_price,
        "exit_reason": exit_reason,
        "bars_held": bars_held,
        "ambiguous": bool(ambiguous),
        "bars_to_target": bars_to_target,
        "bars_to_stop": bars_to_stop,
        "gross_result_r": float(gross),
        "cost_r": float(cost),
        "net_result_r": float(gross - cost) if not math.isnan(gross) else float("nan"),
    }


