def labeling_defaults() -> dict[str, Any]:
    """Default labeling configuration (mirrors ``configs/labeling.yaml``)."""
    return {
        "horizons": [4, 8, 16, 32],
        "reward_r_values": [1.0, 1.5, 2.0],
        "same_bar_policy": "ambiguous",
        "time_barrier_result": "mark_to_market",
        "primary_reward_r": 2.0,
        "primary_horizon": 16,
        "stop_buffer_atr": 0.10,
        "half_spread_price": 0.0,
        "slippage_price": 0.0,
        "commission_r": 0.0,
        "entry_mode": "next_open_after_sweep",
        "atr_period": 14,
    }


def resolve_labeling_config(config: Mapping[str, Any] | None) -> dict[str, Any]:
    """Normalize a (possibly nested) config mapping into flat labeling options.

    Accepts either the merged YAML shape — ``labeling`` / ``stop`` / ``costs``
    / ``entry`` / ``indicators`` sections — or a flat dict with the same keys
    as :func:`labeling_defaults`.  Missing keys keep defaults.  Invalid values
    raise ``ValueError`` naming the offending option.
    """
    cfg = labeling_defaults()

    def pick(*path: str) -> Any:
        node: Any = config or {}
        for key in path:
            if not isinstance(node, Mapping) or key not in node:
                return None
            node = node[key]
        return node

    horizons = pick("labeling", "horizons")
    rewards = pick("labeling", "reward_r_values")
    policy = pick("labeling", "same_bar_policy")
    time_result = pick("labeling", "time_barrier_result")
    primary_r = pick("labeling", "primary_reward_r")
    primary_h = pick("labeling", "primary_horizon")
    buffer_atr = pick("stop", "buffer_atr")
    half_spread = pick("costs", "half_spread_price")
    slippage = pick("costs", "slippage_price")
    commission = pick("costs", "commission_r")
    entry_mode = pick("entry", "mode")
    atr_period = pick("indicators", "atr_period")

    if horizons is not None:
        if (
            not isinstance(horizons, list)
            or not horizons
            or any(not isinstance(h, int) or isinstance(h, bool) or h < 1 for h in horizons)
        ):
            raise ValueError(
                f"resolve_labeling_config: labeling.horizons must be a "
                f"non-empty list of ints >= 1, got {horizons!r}"
            )
        cfg["horizons"] = list(dict.fromkeys(horizons))
    if rewards is not None:
        if (
            not isinstance(rewards, list)
            or not rewards
            or any(
                not isinstance(r, (int, float)) or isinstance(r, bool) or r <= 0
                for r in rewards
            )
        ):
            raise ValueError(
                f"resolve_labeling_config: labeling.reward_r_values must be a "
                f"non-empty list of positive numbers, got {rewards!r}"
            )
        cfg["reward_r_values"] = [float(r) for r in rewards]
    if policy is not None:
        if policy not in SAME_BAR_POLICIES:
            raise ValueError(
                f"resolve_labeling_config: labeling.same_bar_policy must be one "
                f"of {SAME_BAR_POLICIES}, got {policy!r}"
            )
        cfg["same_bar_policy"] = policy
    if time_result is not None:
        if time_result not in TIME_BARRIER_RESULTS:
            raise ValueError(
                f"resolve_labeling_config: labeling.time_barrier_result must be "
                f"one of {TIME_BARRIER_RESULTS}, got {time_result!r}"
            )
        cfg["time_barrier_result"] = time_result

    def _num(name: str, value: Any, minimum: float, strict: bool) -> None:
        if value is None:
            return
        if not isinstance(value, (int, float)) or isinstance(value, bool):
            rel = ">" if strict else ">="
            raise ValueError(
                f"resolve_labeling_config: {name} must be a number {rel} "
                f"{minimum}, got {value!r}"
            )
        bound_ok = (value > minimum) if strict else (value >= minimum)
        if not bound_ok:
            rel = ">" if strict else ">="
            raise ValueError(
                f"resolve_labeling_config: {name} must be a number {rel} "
                f"{minimum}, got {value!r}"
            )

    _num("labeling.primary_reward_r", primary_r, 0.0, strict=True)
    if primary_r is not None:
        cfg["primary_reward_r"] = float(primary_r)
    if primary_h is not None:
        if not isinstance(primary_h, int) or isinstance(primary_h, bool) or primary_h < 1:
            raise ValueError(
                f"resolve_labeling_config: labeling.primary_horizon must be an "
                f"int >= 1, got {primary_h!r}"
            )
        cfg["primary_horizon"] = primary_h
    _num("stop.buffer_atr", buffer_atr, 0.0, strict=False)
    if buffer_atr is not None:
        cfg["stop_buffer_atr"] = float(buffer_atr)
    _num("costs.half_spread_price", half_spread, 0.0, strict=False)
    if half_spread is not None:
        cfg["half_spread_price"] = float(half_spread)
    _num("costs.slippage_price", slippage, 0.0, strict=False)
    if slippage is not None:
        cfg["slippage_price"] = float(slippage)
    _num("costs.commission_r", commission, 0.0, strict=False)
    if commission is not None:
        cfg["commission_r"] = float(commission)

    # Spread/slippage unit guard (Data_Engineer note, task t2): the raw MT5
    # SPREAD column is in POINTS, not price; `costs.*_price` keys are PRICE
    # units (USD/oz).  The separate `entry.spread_price` / `entry.slippage_price`
    # keys are NOT read by the labeling cost model — silently ignoring a
    # nonzero value there would understate costs, so fail loudly instead.
    for name, value in (
        ("entry.spread_price", pick("entry", "spread_price")),
        ("entry.slippage_price", pick("entry", "slippage_price")),
    ):
        if value is not None and (
            not isinstance(value, (int, float)) or isinstance(value, bool) or float(value) > 0
        ):
            raise ValueError(
                f"resolve_labeling_config: {name}={value!r} is not read by the "
                "labeling cost model; set costs.half_spread_price / "
                "costs.slippage_price instead, expressed in PRICE units "
                "(convert the raw MT5 SPREAD points -> price before "
                "configuring)"
            )

    if entry_mode is not None:
        if entry_mode not in ("next_open_after_sweep", "next_open_after_confirmation"):
            raise ValueError(
                f"resolve_labeling_config: entry.mode must be one of "
                f"{{next_open_after_sweep, next_open_after_confirmation}}, "
                f"got {entry_mode!r}"
            )
        cfg["entry_mode"] = entry_mode
    if atr_period is not None:
        if not isinstance(atr_period, int) or isinstance(atr_period, bool) or atr_period < 1:
            raise ValueError(
                f"resolve_labeling_config: indicators.atr_period must be an "
                f"int >= 1, got {atr_period!r}"
            )
        cfg["atr_period"] = atr_period

    # The primary (reward, horizon) combo must exist in the dataset.
    if (
        cfg["primary_reward_r"] not in cfg["reward_r_values"]
        or cfg["primary_horizon"] not in cfg["horizons"]
    ):
        raise ValueError(
            "resolve_labeling_config: primary combo "
            f"({cfg['primary_reward_r']}R, h{cfg['primary_horizon']}) must be "
            "present in labeling.reward_r_values and labeling.horizons"
        )
    return cfg


