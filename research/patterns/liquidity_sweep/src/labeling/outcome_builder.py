def normalize_direction(direction: Any) -> str:
    """Map detector direction values to canonical ``long``/``short``."""
    try:
        return _DIRECTION_ALIASES[str(direction)]
    except KeyError as exc:
        raise ValueError(
            f"normalize_direction: unknown event direction {direction!r}; "
            f"expected long|bullish|short|bearish"
        ) from exc


# ---------------------------------------------------------------------------
# Cost accounting (guide 17)
# ---------------------------------------------------------------------------

def cost_in_r(
    risk: float,
    half_spread_price: float,
    slippage_price: float,
    commission_r: float,
) -> float:
    """Round-trip cost expressed in R units.

    Spread + slippage are paid on entry *and* exit (guide 17.1/17.2:
    ``entry_effective = raw_entry ± (half_spread + slippage)`` and the mirror
    on exit), i.e. ``2 * (half_spread_price + slippage_price)`` in price units,
    converted by ``risk``; ``commission_r`` is already R-denominated.  All
    ``*_price`` arguments are PRICE units (USD/oz); the raw MT5 SPREAD column
    is points and must be converted before it is configured here.
    """
    return 2.0 * (half_spread_price + slippage_price) / risk + commission_r


def gross_result_in_r(direction: str, entry: float, exit_price: float, risk: float) -> float:
    """Raw (pre-cost) trade result in R units from the raw exit price."""
    if math.isnan(float(exit_price)):
        return float("nan")
    if direction == DIRECTION_LONG:
        return (float(exit_price) - float(entry)) / float(risk)
    return (float(entry) - float(exit_price)) / float(risk)


