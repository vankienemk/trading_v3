def format_reward(reward_r: float) -> str:
    """Reward suffix used in column names: 1.0->'1', 1.5->'1_5', 2.0->'2'."""
    return f"{reward_r:g}".replace(".", "_")


def outcome_column(reward_r: float, horizon: int) -> str:
    """Column name of a (reward, horizon) outcome, e.g. ``outcome_2r_h16``."""
    return f"outcome_{format_reward(reward_r)}r_h{horizon}"


def target_column(reward_r: float) -> str:
    """Column name of a reward target price, e.g. ``target_1_5r``."""
    return f"target_{format_reward(reward_r)}r"


def wide_schema_columns(config: Mapping[str, Any] | None = None) -> list[str]:
    """Full ordered column list of :func:`build_event_labels` output."""
    cfg = resolve_labeling_config(config)
    cols: list[str] = [
        "event_id",
        "event_time",
        "direction",
        "level_id",
        "level_price",
        "atr",
        "entry_time",
        "entry_price",
        "stop_price",
        "risk_price",
    ]
    cols.extend(target_column(reward) for reward in cfg["reward_r_values"])
    for horizon in cfg["horizons"]:
        cols.extend(excursion_column_names(horizon))
    cols.extend(outcome_column(reward, horizon) for reward in cfg["reward_r_values"] for horizon in cfg["horizons"])
    cols.extend(_PRIMARY_COLUMNS)
    return cols


